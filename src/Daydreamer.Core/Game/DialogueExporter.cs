using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Daydreamer.Core.Game;

/// <summary>
/// Writes a <see cref="DialogueBook"/> in the two forms the mod reads. The words go in localization entries
/// (<c>DialogueLibrary.Silvian.Greeting.Line1.Text</c>), and the flow goes in a C# class of
/// <c>Dialogue.Define(…)</c> calls, one for each conversation.
/// </summary>
public static partial class DialogueExporter
{
    public const string LibraryKey = "DialogueLibrary";

    [GeneratedRegex(@"^#?(?<r>[0-9A-Fa-f]{2})(?<g>[0-9A-Fa-f]{2})(?<b>[0-9A-Fa-f]{2})$")]
    private static partial Regex HexColorRegex();

    /// <summary>The entry for one conversation, ready to go under the character's group in a localization file.</summary>
    public static HjsonNode ToLocalization(DialogueConversation conversation)
    {
        var node = new HjsonNode(conversation.Name);
        node.Comments.AddRange(conversation.Comments.Select(c => "# " + c));
        for (int i = 0; i < conversation.Lines.Count; i++)
        {
            var line = conversation.Lines[i];
            var lineNode = new HjsonNode($"Line{i + 1}");
            lineNode.Comments.AddRange(line.Comments.Select(c => "# " + c));
            lineNode.Children.Add(new HjsonNode("Text", line.Text));
            for (int c = 0; c < line.Choices.Count; c++)
            {
                var choice = new HjsonNode($"Choice{c + 1}");
                choice.Children.Add(new HjsonNode("Text", line.Choices[c].Text));
                lineNode.Children.Add(choice);
            }
            node.Children.Add(lineNode);
        }
        return node;
    }

    /// <summary>A whole localization file holding just this character, as tModLoader would write it.</summary>
    public static string ToLocalizationFile(DialogueBook book)
    {
        var root = new HjsonNode("");
        var group = root.Ensure(LibraryKey).Ensure(book.Group);
        group.Children.AddRange(book.Conversations.Select(ToLocalization));
        return HjsonWriter.Write(root);
    }

    public static string ClassName(DialogueBook book) => $"{book.Group}WrittenDialogue";

    /// <summary>
    /// The definition file for a character, or null if every conversation stays hand-written. It's a ModSystem rather
    /// than a ModDialogue so it registers after all of them: <c>DialogueRegistry.Add</c> keeps the last one registered
    /// under a key, so a conversation written here takes over from a hand-written one with the same key.
    /// </summary>
    /// <param name="modName">The mod's root namespace.</param>
    /// <param name="newProfiles">Speakers to give a profile, because the mod has none for them yet.</param>
    public static string? ToDefinition(DialogueBook book, string modName, IReadOnlyCollection<string>? newProfiles = null)
    {
        var conversations = book.Conversations.Where(c => !c.HandWritten).ToList();
        if (conversations.Count == 0) return null;

        const string newline = "\r\n";
        var code = new StringBuilder();
        void Line(string text = "") => code.Append(text).Append(newline);

        Line("// <auto-generated>");
        Line($"//   Written by Daydreamer from the document \"{book.Speaker}\". Change the document and export it again:");
        Line("//   anything edited here is replaced the next time it's exported.");
        Line("// </auto-generated>");

        var usings = new List<string>();
        bool usesJobs = conversations.Any(c => c.Ending.Any(e => e.Contains("JobID.")) || c.Lines.Any(l => l.HandIn != null));
        if (usesJobs) usings.Add($"{modName}.Core.Jobs");
        if (conversations.Any(c => c.Lines.Any(l => l.Affects.Any(a => a.Contains("EaseFunction."))))) usings.Add($"{modName}.Utilities");
        usings.AddRange(book.Usings);
        foreach (string name in usings.Distinct().Order(StringComparer.Ordinal)) Line($"using {name};");
        if (usings.Count > 0) Line();

        Line($"namespace {modName}.Core.Dialogue.Definitions;");
        Line();
        Line("/// <summary>");
        Line($"///   {book.Speaker}'s conversations. Text lives in <c>Localization/DialogueLibrary/{book.Group}</c>.");
        Line($"///   Test in game with <c>/dialogue play {book.Group}.{conversations[0].Name}</c>.");
        Line("/// </summary>");
        Line($"sealed class {ClassName(book)} : ModSystem");
        Line("{");
        Line($"    private const string Speaker = {Quoted(book.Speaker)};");
        Line();
        Line("    public override void OnModLoad()");
        Line("    {");

        foreach (string speaker in newProfiles ?? [])
        {
            string color = ColorCode(book.Color) is { } known ? $", Color = {known}" : "";
            Line($"        SpeakerRegistry.Register(new SpeakerProfile {{ Id = {Quoted(speaker)}{color} }});");
            Line();
        }

        for (int i = 0; i < conversations.Count; i++)
        {
            if (i > 0) Line();
            WriteConversation(code, book, conversations[i], newline);
        }

        Line("    }");
        Line("}");
        return code.ToString();
    }

    private static void WriteConversation(StringBuilder code, DialogueBook book, DialogueConversation conversation, string newline)
    {
        const string chain = "            ";
        code.Append($"        Dialogue.Define({Quoted($"{book.Group}.{conversation.Name}")})").Append(newline);
        foreach (var line in conversation.Lines)
        {
            string speaker = line.Speaker.Equals(book.Speaker, StringComparison.Ordinal) ? "Speaker" : Quoted(line.Speaker);
            code.Append(chain).Append($".Line({speaker}, emote: {line.Emote.ToString(CultureInfo.InvariantCulture)}, speed: {DialogueEffects.FloatCode(line.Speed)}{Affects(line)})").Append(newline);

            if (line.HandIn != null)
            {
                code.Append(chain).Append("    ").Append($".HandIn(JobID.{line.HandIn})").Append(newline);
                continue;
            }
            foreach (var choice in line.Choices)
                code.Append(chain).Append("    ").Append(ChoiceCall(choice)).Append(newline);
        }
        foreach (string ending in conversation.Ending)
            code.Append(chain).Append(ending).Append(newline);
        code.Append(chain).Append(".Register();").Append(newline);
    }

    private static string Affects(DialogueLine line) => line.Affects.Count switch
    {
        0 => "",
        1 => $", {line.Affects[0]}",
        _ => $", [{string.Join(", ", line.Affects)}]",
    };

    private static string ChoiceCall(DialogueChoice choice)
    {
        var args = new List<string>();
        if (choice.Branch != null) args.Add(Quoted(choice.Branch));
        if (choice.OnSelected != null) args.Add($"onSelected: () => {choice.OnSelected}");
        if (choice.Dead) args.Add("dead: true");
        return $".Choice({string.Join(", ", args)})";
    }

    /// <summary>A panel color as C#: "255 110 80" or "#FF6E50" → <c>new(255, 110, 80)</c>.</summary>
    private static string? ColorCode(string? color)
    {
        if (string.IsNullOrWhiteSpace(color)) return null;
        var hex = HexColorRegex().Match(color.Trim());
        if (hex.Success)
        {
            static int Part(Group g) => int.Parse(g.Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            return $"new({Part(hex.Groups["r"])}, {Part(hex.Groups["g"])}, {Part(hex.Groups["b"])})";
        }
        var parts = color.Split([' ', ','], StringSplitOptions.RemoveEmptyEntries);
        return parts.Length == 3 && parts.All(p => byte.TryParse(p, out _)) ? $"new({parts[0]}, {parts[1]}, {parts[2]})" : null;
    }

    private static string Quoted(string text) => $"\"{text.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"";
}
